impl DsaPublicKey {
    /// Return the prime modulus.
    #[must_use]
    pub fn modulus(&self) -> &BigUint {
        &self.p
    }

    /// Return the prime subgroup order.
    #[must_use]
    pub fn subgroup_order(&self) -> &BigUint {
        &self.q
    }

    /// Return the subgroup generator.
    #[must_use]
    pub fn generator(&self) -> &BigUint {
        &self.g
    }

    /// Return the public component `y = g^x mod p`.
    #[must_use]
    pub fn public_component(&self) -> &BigUint {
        &self.y
    }

    /// A public key from validated domain parameters and the public
    /// component `y`.
    ///
    /// `y` must lie in the order-`q` subgroup: `1 < y < p` and
    /// `y^q ≡ 1 (mod p)`, the FFC full public-key validation of SP 800-56A
    /// Rev. 3 §5.6.2.3.1 (FIPS 186-4 leaves public-key assurance to SP
    /// 800-89). Returns `None` otherwise. The group itself was validated when
    /// `params` was built, so nothing about it is recomputed here.
    #[must_use]
    pub fn from_public_component(params: &DsaParams, y: BigUint) -> Option<Self> {
        let (p, q, g) = (
            params.modulus(),
            params.subgroup_order(),
            params.generator(),
        );
        if !is_in_prime_order_subgroup(&y, q, p) {
            return None;
        }
        Some(Self {
            p: p.clone(),
            q: q.clone(),
            g: g.clone(),
            y,
            p_ctx: MontgomeryContext::new(p).ok(),
            q_ctx: MontgomeryContext::new(q).ok(),
        })
    }

    /// Extract the domain parameters `(p, q, g)` as a standalone
    /// [`DsaParams`], suitable for generating further key pairs in the group.
    ///
    /// A parsed public key has had only the structural (fixed-base) checks,
    /// but a `DsaParams` is a group this crate will generate secrets over, so
    /// this runs the hardened validation of [`DsaParams::new`] and returns
    /// `None` if the parameters do not survive it. Keys store no seed record,
    /// so the parameters returned have none.
    #[must_use]
    pub fn params(&self) -> Option<DsaParams> {
        DsaParams::new(self.p.clone(), self.q.clone(), self.g.clone())
    }

    /// Hash one message with `H`, then verify the resulting digest.
    #[must_use]
    pub fn verify_message<H: Digest>(&self, message: &[u8], signature: &DsaSignature) -> bool {
        let digest = H::digest(message);
        self.verify(&digest, signature)
    }

    /// Hash one message with `H`, then verify a serialized signature.
    #[must_use]
    pub fn verify_message_bytes<H: Digest>(&self, message: &[u8], signature: &[u8]) -> bool {
        let digest = H::digest(message);
        self.verify_bytes(&digest, signature)
    }

    /// Verify a signature over an explicit integer representative.
    #[must_use]
    pub fn verify_digest_scalar(&self, hash: &BigUint, signature: &DsaSignature) -> bool {
        if signature.r.is_zero()
            || signature.s.is_zero()
            || signature.r >= self.q
            || signature.s >= self.q
        {
            return false;
        }

        let Some(w) = mod_inverse(&signature.s, &self.q) else {
            return false;
        };
        // FIPS 186-4 verification variables: `w = s^-1 mod q`,
        // `z = leftmost-N-bits(H(M)) mod q`, then `u1 = z * w mod q` and
        // `u2 = r * w mod q`.
        let z = hash.rem(&self.q);
        let u1 = if let Some(ctx) = &self.q_ctx {
            ctx.mul(&z, &w)
        } else {
            BigUint::mod_mul(&z, &w, &self.q)
        };
        let u2 = if let Some(ctx) = &self.q_ctx {
            ctx.mul(&signature.r, &w)
        } else {
            BigUint::mod_mul(&signature.r, &w, &self.q)
        };

        let g_term = if let Some(ctx) = &self.p_ctx {
            ctx.pow(&self.g, &u1)
        } else {
            mod_pow(&self.g, &u1, &self.p)
        };
        let y_term = if let Some(ctx) = &self.p_ctx {
            ctx.pow(&self.y, &u2)
        } else {
            mod_pow(&self.y, &u2, &self.p)
        };
        let combined = if let Some(ctx) = &self.p_ctx {
            ctx.mul(&g_term, &y_term)
        } else {
            BigUint::mod_mul(&g_term, &y_term, &self.p)
        };

        combined.rem(&self.q) == signature.r
    }

    /// Verify a signature over the provided digest bytes.
    ///
    /// The digest is cut to its leftmost `min(N, outlen)` bits, `N = bits(q)`,
    /// as FIPS 186-4 §4.7 step 2 computes `z`.
    #[must_use]
    pub fn verify(&self, digest: &[u8], signature: &DsaSignature) -> bool {
        self.verify_digest_scalar(&digest_to_scalar(digest, &self.q), signature)
    }

    /// Verify a byte-encoded signature produced by
    /// [`DsaPrivateKey::sign_digest_bytes`].
    #[must_use]
    pub fn verify_bytes(&self, digest: &[u8], signature: &[u8]) -> bool {
        let Some(signature) = DsaSignature::from_key_blob(signature) else {
            return false;
        };
        self.verify(digest, &signature)
    }

    /// Schema fields for the crate-defined serialization formats.
    fn serial_fields(&self) -> Vec<BigUint> {
        vec![
            self.p.clone(),
            self.q.clone(),
            self.g.clone(),
            self.y.clone(),
        ]
    }

    /// Validate schema fields and rebuild the key with its derived state.
    ///
    /// Structural validation (public material): fixed-base primality of `p`
    /// and `q`, the subgroup relations for `g`, and `y` in the order-`q`
    /// subgroup (`1 < y < p`, `y^q ≡ 1 (mod p)`). For odd `q` the check on `y`
    /// is the FFC full public-key validation of SP 800-56A Rev. 3 §5.6.2.3.1;
    /// FIPS 186-4 leaves the assurance of public-key validity to SP 800-89.
    fn from_serial_fields(fields: Vec<BigUint>) -> Option<Self> {
        let mut fields = fields.into_iter();
        let p = fields.next()?;
        let q = fields.next()?;
        let g = fields.next()?;
        let y = fields.next()?;
        if !validate_prime_order_group(&p, &q, &g, PrimalityPolicy::Structural)
            || !is_in_prime_order_subgroup(&y, &q, &p)
        {
            return None;
        }
        let p_ctx = MontgomeryContext::new(&p).ok();
        let q_ctx = MontgomeryContext::new(&q).ok();
        Some(Self {
            p,
            q,
            g,
            y,
            p_ctx,
            q_ctx,
        })
    }
}

