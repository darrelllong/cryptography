    #[test]
    fn verify_rejects_r_and_s_outside_subgroup_range() {
        // FIPS 186-4 §4.7 step 1: reject unless 0 < r < q and 0 < s < q.
        let (public, private) = derive_small_reference_key();
        let digest = [0x12, 0x34];
        let good = private
            .sign_digest_with_nonce(&digest, &u(5))
            .expect("valid nonce");
        assert!(public.verify(&digest, &good));
        let q = public.subgroup_order().clone();
        for (r, s) in [
            (BigUint::zero(), good.s.clone()),
            (good.r.clone(), BigUint::zero()),
            (q.clone(), good.s.clone()),
            (good.r.clone(), q.clone()),
            (q.add(&good.r), good.s.clone()),
            (good.r.clone(), q.add(&good.s)),
        ] {
            let bad = DsaSignature { r, s };
            assert!(!public.verify(&digest, &bad), "{bad:?}");
        }
        // The DER decoder already refuses zero components.
        let zero_r = encode_biguints(&[&BigUint::zero(), &good.s]);
        assert!(DsaSignature::from_der(&zero_r).is_none());
        assert!(!public.verify_bytes(&digest, &zero_r));
    }

    #[test]
    fn public_key_parse_rejects_tampered_fields() {
        // p = 65543, q = 32771, g = 4, y = 4^3 = 64: valid.
        assert!(
            DsaPublicKey::from_key_blob(&encode_biguints(&[&u(P), &u(Q), &u(G), &u(64)])).is_some()
        );
        // y outside the subgroup: 1 (identity), 0, p, p - 1 (order 2), and
        // the quadratic non-residues 5 and q.
        for y in [1u64, 0, P, P - 1, 5, Q] {
            let blob = encode_biguints(&[&u(P), &u(Q), &u(G), &u(y)]);
            assert!(DsaPublicKey::from_key_blob(&blob).is_none(), "y = {y}");
        }
        // Composite p (65545 = 5 · 13109), composite q (32769 = 3 · 10923),
        // a prime q not dividing p - 1 (32779), q >= p, g outside the
        // subgroup, g = 1, a subgroup order below the size policy (q = 11
        // in Z_23*), and the wrong field count.
        for fields in [
            [65545u64, Q, G, 64],
            [P, 32769, G, 64],
            [P, 32779, G, 64],
            [P, P, G, 64],
            [P, Q, 5, 64],
            [P, Q, 1, 64],
            [23, 11, 4, 18],
        ] {
            let values: Vec<BigUint> = fields.iter().map(|&v| u(v)).collect();
            let refs: Vec<&BigUint> = values.iter().collect();
            assert!(
                DsaPublicKey::from_key_blob(&encode_biguints(&refs)).is_none(),
                "{fields:?}"
            );
        }
        assert!(DsaPublicKey::from_key_blob(&encode_biguints(&[&u(P), &u(Q), &u(G)])).is_none());
    }

