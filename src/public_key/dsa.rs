impl DsaPrivateKey {
    /// Return the prime modulus.
    #[must_use]
    pub fn modulus(&self) -> &BigUint {
        &self.p
    }

    /// Return the prime subgroup order.
    #[must_use]
    pub fn subgroup_order(&self) -> &BigUint {
        &self.q
    }

    /// Return the subgroup generator.
    #[must_use]
    pub fn generator(&self) -> &BigUint {
        &self.g
    }

    /// Return the private exponent `x`.
    #[must_use]
    pub fn exponent(&self) -> &BigUint {
        &self.x
    }

    /// Extract the domain parameters `(p, q, g)` as a standalone
    /// [`DsaParams`], suitable for generating further key pairs in the group.
    ///
    /// A private key's group has already passed the hardened validation (at
    /// generation or at parse time), so no further check is needed. Keys store
    /// no seed record, so the parameters returned have none.
    #[must_use]
    pub fn params(&self) -> DsaParams {
        DsaParams::from_domain(FfcDomain::from_validated_parts(
            self.p.clone(),
            self.q.clone(),
            self.g.clone(),
        ))
    }

    /// Derive the matching public key from this private key.
    #[must_use]
    pub fn to_public_key(&self) -> DsaPublicKey {
        DsaPublicKey {
            p: self.p.clone(),
            q: self.q.clone(),
            g: self.g.clone(),
            y: self.y.clone(),
            p_ctx: self.p_ctx.clone(),
            q_ctx: self.q_ctx.clone(),
        }
    }

    /// Sign with an explicit nonce `k`.
    ///
    /// `DSA` uses a fresh `k` in `[1, q)` for every signature. This lower-level
    /// entry point keeps the arithmetic explicit for deterministic tests.
    ///
    /// Reusing the same `k` for two different messages with the same key
    /// immediately reveals the private exponent. Outside of fixed vectors,
    /// prefer [`Self::sign_digest`] or [`Self::sign_message`].
    #[must_use]
    pub fn sign_digest_with_nonce(&self, digest: &[u8], nonce: &BigUint) -> Option<DsaSignature> {
        if nonce.is_zero() || nonce >= &self.q {
            return None;
        }

        let z = digest_to_scalar(digest, &self.q);
        let r = if let Some(ctx) = &self.p_ctx {
            ctx.pow(&self.g, nonce)
        } else {
            mod_pow(&self.g, nonce, &self.p)
        }
        .rem(&self.q);
        if r.is_zero() {
            return None;
        }

        let nonce_inv = mod_inverse(nonce, &self.q)?;
        let xr = if let Some(ctx) = &self.q_ctx {
            ctx.mul(&self.x, &r)
        } else {
            BigUint::mod_mul(&self.x, &r, &self.q)
        };
        let sum = z.add(&xr).rem(&self.q);
        let s = if let Some(ctx) = &self.q_ctx {
            ctx.mul(&nonce_inv, &sum)
        } else {
            BigUint::mod_mul(&nonce_inv, &sum, &self.q)
        };
        if s.is_zero() {
            return None;
        }

        Some(DsaSignature { r, s })
    }

    /// Sign a pre-hashed digest using RFC 6979 deterministic nonce derivation.
    ///
    /// A `k` that gives `r = 0` or `s = 0` is rejected and the next candidate
    /// of RFC 6979 §3.2 step h.3 taken, as §3.2 prescribes; after
    /// [`MAX_NONCE_DRAWS`] rejected candidates this returns `None` instead of
    /// continuing. Every `k` is rejected only in a group whose subgroup
    /// consists of `1` and multiples of `q` — the order-2 subgroup
    /// `{1, p − 1}` — which the size policy (`q ≥ 2^15`) excludes, so for a
    /// key this crate built or parsed the bound is never reached.
    #[must_use]
    pub fn sign_digest<H: Digest>(&self, digest: &[u8]) -> Option<DsaSignature> {
        let mut nonces = NonceGenerator::<H>::new(&self.q, &self.x, digest)?;
        (0..MAX_NONCE_DRAWS).find_map(|_| self.sign_digest_with_nonce(digest, &nonces.next()))
    }

    /// Sign a digest using a fresh random nonce `k` in `[1, q)` from `rng`.
    ///
    /// FIPS 186-4 §4.6 has signing draw a new `k` whenever `r = 0` or
    /// `s = 0`. A working random source is rejected with probability about
    /// `2/q` per draw, so this returns after the first draw in practice and
    /// returns `None` only after [`MAX_NONCE_DRAWS`] consecutive draws have
    /// all been rejected: probability about `(2/q)^64` for a working source,
    /// and the signature of a source that repeats an in-range `k` this key
    /// and digest reject.
    ///
    /// # Panics
    ///
    /// Panics on a source that stalls below the range — one that repeats a
    /// value the sampler itself rejects for 256 draws — as
    /// [`random_nonzero_below`] does; that report comes before this
    /// function's own bound can.
    #[must_use]
    pub fn sign_digest_with_rng<R: Csprng>(
        &self,
        digest: &[u8],
        rng: &mut R,
    ) -> Option<DsaSignature> {
        (0..MAX_NONCE_DRAWS).find_map(|_| {
            let nonce = random_nonzero_below(rng, &self.q)?;
            self.sign_digest_with_nonce(digest, &nonce)
        })
    }

    /// Hash one message with `H`, then sign deterministically.
    #[must_use]
    pub fn sign_message<H: Digest>(&self, message: &[u8]) -> Option<DsaSignature> {
        let digest = H::digest(message);
        self.sign_digest::<H>(&digest)
    }

    /// Hash one message with `H`, then sign with randomized nonces.
    #[must_use]
    pub fn sign_message_with_rng<H: Digest, R: Csprng>(
        &self,
        message: &[u8],
        rng: &mut R,
    ) -> Option<DsaSignature> {
        let digest = H::digest(message);
        self.sign_digest_with_rng(&digest, rng)
    }

    /// Sign a digest deterministically and return serialized signature bytes.
    #[must_use]
    pub fn sign_digest_bytes<H: Digest>(&self, digest: &[u8]) -> Option<Vec<u8>> {
        let signature = self.sign_digest::<H>(digest)?;
        Some(signature.to_key_blob())
    }

    /// Sign a digest with randomized nonces and return serialized signature bytes.
    #[must_use]
    pub fn sign_digest_bytes_with_rng<H: Digest, R: Csprng>(
        &self,
        digest: &[u8],
        rng: &mut R,
    ) -> Option<Vec<u8>> {
        let signature = self.sign_digest_with_rng(digest, rng)?;
        Some(signature.to_key_blob())
    }

    /// Hash one message with `H`, then sign and serialize deterministically.
    #[must_use]
    pub fn sign_message_bytes<H: Digest>(&self, message: &[u8]) -> Option<Vec<u8>> {
        let signature = self.sign_message::<H>(message)?;
        Some(signature.to_key_blob())
    }

    /// Hash one message with `H`, then sign and serialize with randomized nonces.
    #[must_use]
    pub fn sign_message_bytes_with_rng<H: Digest, R: Csprng>(
        &self,
        message: &[u8],
        rng: &mut R,
    ) -> Option<Vec<u8>> {
        let signature = self.sign_message_with_rng::<H, R>(message, rng)?;
        Some(signature.to_key_blob())
    }

    /// Schema fields for the crate-defined serialization formats.
    fn serial_fields(&self) -> Vec<BigUint> {
        vec![
            self.p.clone(),
            self.q.clone(),
            self.g.clone(),
            self.x.clone(),
        ]
    }

    /// Validate schema fields and rebuild the key with its derived state.
    ///
    /// Full validation (private material): hardened primality of `p` and
    /// `q`, the subgroup relations for `g`, `x ∈ [1, q)`, and `y` recomputed
    /// from `x` rather than carried.
    fn from_serial_fields(fields: Vec<BigUint>) -> Option<Self> {
        let mut fields = fields.into_iter();
        let p = fields.next()?;
        let q = fields.next()?;
        let g = fields.next()?;
        let x = fields.next()?;
        if !validate_prime_order_group(&p, &q, &g, PrimalityPolicy::Hardened)
            || x.is_zero()
            || x >= q
        {
            return None;
        }
        Some(Dsa::key_pair(&p, &q, &g, x).1)
    }
}

