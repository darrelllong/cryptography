    #[test]
    fn signature_der_matches_key_blob() {
        let signature = DsaSignature {
            r: BigUint::from_u64(0x81),
            s: BigUint::from_u64(9),
        };
        let der = signature.to_der();
        assert_eq!(der, [0x30, 0x07, 0x02, 0x02, 0x00, 0x81, 0x02, 0x01, 0x09]);
        assert_eq!(signature.to_key_blob(), der);
        assert_eq!(DsaSignature::from_der(&der), Some(signature));
        // Non-minimal INTEGER for s is not DER.
        let ber = [0x30, 0x08, 0x02, 0x02, 0x00, 0x81, 0x02, 0x02, 0x00, 0x09];
        assert!(DsaSignature::from_der(&ber).is_none());
    }

