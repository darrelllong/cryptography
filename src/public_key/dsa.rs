    /// A random source that plays back a script of two-byte draws and counts
    /// them. Under the 16-bit `q` the nonce sampler asks for exactly two
    /// bytes per draw and accepts any value in `[1, q)`, so each entry is the
    /// nonce of one draw; once the script is used up the last entry repeats.
    struct ScriptedRng {
        script: Vec<u16>,
        draws: usize,
    }

    impl ScriptedRng {
        fn new(script: &[u16]) -> Self {
            Self {
                script: script.to_vec(),
                draws: 0,
            }
        }
    }

    impl crate::Csprng for ScriptedRng {
        fn fill_bytes(&mut self, out: &mut [u8]) {
            assert_eq!(out.len(), 2, "a 16-bit q draws two bytes");
            let value = self.script[self.draws.min(self.script.len() - 1)];
            out.copy_from_slice(&value.to_be_bytes());
            self.draws += 1;
        }
    }

    /// On the reference key (`g = 4`, `x = 3`) the nonce `k = 1` gives `r = 4`
    /// and `x·r = 12`, so the digest `0x7ff7`, whose value is `z = 32759 ≡
    /// −12 (mod q)`, makes `s = z + xr ≡ 0`. FIPS 186-4 §4.6 then calls for a
    /// new `k`: a source that yields that `k` once and then a good one signs
    /// on the second draw, and a source stuck on it is refused with `None`
    /// after exactly `MAX_NONCE_DRAWS` draws.
    #[test]
    fn randomized_signing_retries_a_zeroing_nonce_and_refuses_a_source_stuck_on_it() {
        let (public, private) = derive_small_reference_key();
        let digest = [0x7f, 0xf7];
        assert!(private
            .sign_digest_with_nonce(&digest, &BigUint::one())
            .is_none());
        let good = private
            .sign_digest_with_nonce(&digest, &u(5))
            .expect("k = 5 signs this digest");

        let mut retrying = ScriptedRng::new(&[1, 5]);
        let signature = private
            .sign_digest_with_rng(&digest, &mut retrying)
            .expect("the second draw signs");
        assert_eq!(signature, good);
        assert!(public.verify(&digest, &signature));
        assert_eq!(
            retrying.draws, 2,
            "exactly two draws: the rejected k and the good one"
        );

        let mut stuck = ScriptedRng::new(&[1]);
        assert_eq!(private.sign_digest_with_rng(&digest, &mut stuck), None);
        assert_eq!(stuck.draws, MAX_NONCE_DRAWS);
    }

