//! Digital Signature Algorithm (`DSA`), as FIPS 186-4 specifies it
//! (`pubs/fips186-4.pdf`). FIPS 186-5 no longer approves `DSA` for generating
//! signatures and allows it only for verifying signatures made earlier; its
//! specification now exists only in FIPS 186-4.
//!
//! `DSA` works in a prime-order subgroup: a prime modulus `p`, a prime
//! subgroup order `q` dividing `p - 1`, and a generator `g` of the order-`q`
//! subgroup — the domain parameters. Signing and verification then operate
//! entirely modulo `q`, while the group actions still happen modulo `p`.
//!
//! What follows FIPS 186-4, and what does not:
//!
//! - [`Dsa::generate_params`] generates domain parameters by Appendix A.1.1.2
//!   (`p` and `q`) and A.2.3 (`g`, with `index = 1`, A.2.3's own example value
//!   for digital signatures) at the four `(L, N)` pairs of §4.2, and keeps the
//!   seed record that A.1.1.3 and A.2.4 validate ([`DsaParams::with_seed`]).
//! - [`Dsa::generate`] draws the private key `x` uniformly from `[1, q − 1]`,
//!   the distribution of Appendix B.1.2 (key pair generation by testing
//!   candidates).
//! - [`DsaPrivateKey::sign_digest_with_rng`] draws the per-message `k`
//!   uniformly from `[1, q − 1]`, the distribution of Appendix B.2.2, and
//!   computes `r` and `s` as §4.6 does, drawing a new `k` if either is zero.
//! - [`DsaPublicKey::verify`] is §4.7, including step 1's range check on `r`
//!   and `s`; digests are cut to their leftmost `min(N, outlen)` bits.
//! - [`DsaPrivateKey::sign_digest`] derives `k` deterministically by RFC 6979.
//!   FIPS 186-4 Appendix B.2 allows only its two random methods "or another
//!   approved method", and RFC 6979 is not one: those signatures verify under
//!   FIPS 186-4 but are not generated by it.
//! - [`Dsa::generate_toy_params`] makes groups smaller than any size FIPS
//!   186-4 defines, for tests, and [`Dsa::from_secret_exponent`] accepts any
//!   valid group; neither is FIPS 186-4 unless its inputs are. Every group,
//!   standard or not, must have `q ≥ 2^15` and `p` of at most 16384 bits
//!   ([`MIN_SUBGROUP_ORDER_BITS`], [`MAX_MODULUS_BITS`],
//!   [`MAX_SUBGROUP_ORDER_BITS`]).
//! - Both signers give up after [`MAX_NONCE_DRAWS`] rejected `k` and return
//!   `None`; a working source and a valid group never reach that bound.
//!
//! ## Timing
//!
//! The modular exponentiations are rump's, which are variable-time: the
//! number of multiplications in `g^k mod p` follows the bit length and
//! Hamming weight of the exponent. Signing therefore leaks the bit length of
//! the per-message secret `k` through its running time, and the lattice
//! attacks on DSA recover `x` from a few bits of many `k`s. `x` itself enters
//! signing only through the multiplication `x·r mod q`, whose cost does not
//! depend on `x`'s value beyond its length. Verification handles no secret.
//! Nothing here is safe against an adversary who can time the signer.
//!
//! [`MIN_SUBGROUP_ORDER_BITS`]: crate::public_key::primes::MIN_SUBGROUP_ORDER_BITS
//! [`MAX_MODULUS_BITS`]: crate::public_key::primes::MAX_MODULUS_BITS
//! [`MAX_SUBGROUP_ORDER_BITS`]: crate::public_key::primes::MAX_SUBGROUP_ORDER_BITS
//!
//! ## Key encodings
//!
//! The crate-defined `to_key_blob`, `to_pem` and `to_xml` forms remain the
//! defaults. The standard encodings sit beside them:
//! [`DsaPublicKey::to_spki_der`] (RFC 3279 §2.3.2 `SubjectPublicKeyInfo`, PEM
//! label `PUBLIC KEY`), [`DsaPrivateKey::to_pkcs8_der`] (RFC 5958
//! `OneAsymmetricKey`, whose §2 gives a DSA private key as an `INTEGER`; PEM
//! label `PRIVATE KEY`) and [`DsaParams::to_der`] (`Dss-Parms`), each with a
//! decoder.

