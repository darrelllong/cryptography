impl DsaSignature {
    /// Return the first signature component.
    #[must_use]
    pub fn r(&self) -> &BigUint {
        &self.r
    }

    /// Return the second signature component.
    #[must_use]
    pub fn s(&self) -> &BigUint {
        &self.s
    }

    /// Encode as the X9.62 / RFC 3279 §2.2.2 `Dss-Sig-Value`:
    /// `SEQUENCE { r INTEGER, s INTEGER }` in strict DER.
    #[must_use]
    pub fn to_der(&self) -> Vec<u8> {
        encode_biguints(&[&self.r, &self.s])
    }

    /// Decode a `Dss-Sig-Value`.
    ///
    /// Strict DER only. Zero components are rejected here; the range check
    /// against the subgroup order `q` happens during verification because
    /// the structure does not carry `q`.
    #[must_use]
    pub fn from_der(der: &[u8]) -> Option<Self> {
        let mut fields = decode_biguints(der)?.into_iter();
        let r = fields.next()?;
        let s = fields.next()?;
        if fields.next().is_some() || r.is_zero() || s.is_zero() {
            return None;
        }
        Some(Self { r, s })
    }

    /// The crate-defined signature blob, byte-identical to [`Self::to_der`].
    #[must_use]
    pub fn to_key_blob(&self) -> Vec<u8> {
        self.to_der()
    }

    /// Decode the crate-defined signature blob; identical to
    /// [`Self::from_der`].
    #[must_use]
    pub fn from_key_blob(blob: &[u8]) -> Option<Self> {
        Self::from_der(blob)
    }
}

impl Dsa {
    /// Derive a `DSA` key pair from explicit subgroup parameters and secret
    /// exponent: the parameters go through [`DsaParams::new`] — a group this
    /// crate signs under with the caller's secret gets the hardened
    /// validation — and the key pair through [`Dsa::with_secret_exponent`].
    #[must_use]
    pub fn from_secret_exponent(
        prime: &BigUint,
        subgroup_order: &BigUint,
        generator: &BigUint,
        secret: &BigUint,
    ) -> Option<(DsaPublicKey, DsaPrivateKey)> {
        let params = DsaParams::new(prime.clone(), subgroup_order.clone(), generator.clone())?;
        Self::with_secret_exponent(&params, secret)
    }

    /// Derive a `DSA` key pair from validated domain parameters and the
    /// secret exponent `x`. Returns `None` unless `x ∈ [1, q − 1]`, the range
    /// FIPS 186-4 §4.1 gives it; `y = g^x mod p` is computed here.
    #[must_use]
    pub fn with_secret_exponent(
        params: &DsaParams,
        secret: &BigUint,
    ) -> Option<(DsaPublicKey, DsaPrivateKey)> {
        let (p, q, g) = (
            params.modulus(),
            params.subgroup_order(),
            params.generator(),
        );
        if secret.is_zero() || secret >= q {
            return None;
        }
        Some(Self::key_pair(p, q, g, secret.clone()))
    }

    /// The key pair of the secret `x ∈ [1, q)` over a validated group, with
    /// its cached Montgomery contexts.
    fn key_pair(
        p: &BigUint,
        q: &BigUint,
        g: &BigUint,
        x: BigUint,
    ) -> (DsaPublicKey, DsaPrivateKey) {
        let p_ctx = MontgomeryContext::new(p).ok();
        let q_ctx = MontgomeryContext::new(q).ok();
        let y = match &p_ctx {
            Some(ctx) => ctx.pow(g, &x),
            None => mod_pow(g, &x, p),
        };
        (
            DsaPublicKey {
                p: p.clone(),
                q: q.clone(),
                g: g.clone(),
                y: y.clone(),
                p_ctx: p_ctx.clone(),
                q_ctx: q_ctx.clone(),
            },
            DsaPrivateKey {
                p: p.clone(),
                q: q.clone(),
                g: g.clone(),
                x,
                y,
                p_ctx,
                q_ctx,
            },
        )
    }

    /// Generate `DSA` domain parameters by FIPS 186-4: `p` and `q` by
    /// Appendix A.1.1.2 with `hash` and an `N`-bit seed drawn from `rng`, then
    /// `g` by A.2.3 with index 1. The parameters carry their seed record, so
    /// any FIPS 186-4 validator — [`DsaParams::with_seed`] among them — can
    /// check them.
    ///
    /// `size` is one of the §4.2 pairs. Returns `None` if `hash` is shorter
    /// than `N` bits (A.1.1.2): SHA-224 serves only `N = 160` and `N = 224`.
    ///
    /// # Panics
    ///
    /// Panics on a source that stalls, as the primality test's base sampler
    /// ([`random_below`](crate::public_key::primes::random_below)) does after
    /// 256 consecutive rejected draws.
    #[must_use]
    pub fn generate_params<R: Csprng>(
        rng: &mut R,
        size: FfcParameterSize,
        hash: FfcHash,
    ) -> Option<DsaParams> {
        FfcDomain::generate_fips186_4(rng, size, hash, DIGITAL_SIGNATURE_INDEX)
            .map(DsaParams::from_domain)
    }

    /// Generate a small group for tests. **This is not FIPS 186-4**: the sizes
    /// are ones §4.2 does not list, and the construction follows no standard.
    ///
    /// Accepts `bits` from 19 to 1023 and returns `None` otherwise, so every
    /// size FIPS 186-4 covers goes through [`Dsa::generate_params`]. The
    /// subgroup order has `clamp(⌊bits/4⌋, 16, 256)` bits, `p = kq + 1` for a
    /// random even `k`, and `g = h^k mod p` for a random `h`. No seed is kept:
    /// the parameters can be checked for structure, not for how they were made.
    ///
    /// # Panics
    ///
    /// Panics on a stalled or constant source, as the prime and cofactor
    /// samplers do (see
    /// [`random_probable_prime`](crate::public_key::primes::random_probable_prime)).
    #[must_use]
    pub fn generate_toy_params<R: Csprng>(rng: &mut R, bits: usize) -> Option<DsaParams> {
        FfcDomain::generate_toy(rng, bits).map(DsaParams::from_domain)
    }

    /// Generate a `DSA` key pair from existing domain parameters.
    ///
    /// `x` is uniform on `[1, q − 1]`, the distribution FIPS 186-4 Appendix
    /// B.1.2 produces for parameters of an approved size.
    ///
    /// # Panics
    ///
    /// Panics on a source that stalls, as [`random_nonzero_below`] does
    /// after 256 consecutive rejected draws.
    #[must_use]
    pub fn generate<R: Csprng>(params: &DsaParams, rng: &mut R) -> (DsaPublicKey, DsaPrivateKey) {
        let (p, q, g) = (
            params.modulus(),
            params.subgroup_order(),
            params.generator(),
        );
        // Every `DsaParams` has a prime subgroup order q >= 2^15, so `[1, q)`
        // is never empty.
        let secret = random_nonzero_below(rng, q)
            .expect("validated DSA parameters have a prime subgroup order q >= 2^15");
        Self::key_pair(p, q, g, secret)
    }
}

/// FIPS 186-4 digest representative reduction.
///
/// §4.6 and §4.7 keep the leftmost `min(N, outlen)` bits of the hash, with
/// `N = bits(q)`. The shift amount is derived from the original digest width,
/// not the width after leading-zero trimming.
fn digest_to_scalar(digest: &[u8], modulus: &BigUint) -> BigUint {
    bits_to_int(digest, modulus.bits())
}

