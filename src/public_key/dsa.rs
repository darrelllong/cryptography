/// `DSA` domain parameters `(p, q, g {, seed record})`.
///
/// Many key pairs can share one set. Every instance was generated here or
/// validated on the way in ([`DsaParams::new`], [`DsaParams::with_seed`], the
/// parsers), which is why the fields are private. Parameters from
/// [`Dsa::generate_params`] or [`DsaParams::with_seed`] carry the FIPS 186-4
/// seed record a third party needs to validate them ([`DsaParams::seed`]);
/// others carry none.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DsaParams {
    domain: FfcDomain,
}

/// Public key for `DSA`.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DsaPublicKey {
    /// Prime modulus `p`.
    p: BigUint,
    /// Prime subgroup order `q`.
    q: BigUint,
    /// Generator `g` of the order-`q` subgroup.
    g: BigUint,
    /// Public component `y = g^x mod p`.
    y: BigUint,
    /// Cached Montgomery context for arithmetic modulo `p`.
    p_ctx: Option<MontgomeryContext>,
    /// Cached Montgomery context for arithmetic modulo `q`.
    q_ctx: Option<MontgomeryContext>,
}

/// Private key for `DSA`.
#[derive(Clone, Eq, PartialEq)]
pub struct DsaPrivateKey {
    /// Prime modulus `p`.
    p: BigUint,
    /// Prime subgroup order `q`.
    q: BigUint,
    /// Generator `g` of the order-`q` subgroup.
    g: BigUint,
    /// Secret exponent `x`.
    x: BigUint,
    /// Cached public component `y = g^x mod p`.
    y: BigUint,
    /// Cached Montgomery context for arithmetic modulo `p`.
    p_ctx: Option<MontgomeryContext>,
    /// Cached Montgomery context for arithmetic modulo `q`.
    q_ctx: Option<MontgomeryContext>,
}

/// Raw `DSA` signature pair `(r, s)`.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DsaSignature {
    r: BigUint,
    s: BigUint,
}

