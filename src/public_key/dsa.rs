    /// RFC 6979 §3.2 step h.3: a candidate that gives `r = 0` or `s = 0` is
    /// rejected and the next one taken. Both cases, found by an independent
    /// HMAC-SHA-256 computation of the §3.2 stream over each group:
    ///
    /// - `r = 0`: in `Z_1179757*` (`p = 36q + 1`, `q = 32771`) the subgroup
    ///   element `557107 = 17q` is a multiple of `q`; with `g = 2^36 mod p =
    ///   991000`, `x = 3` and the digest `0x13a4`, the first candidate
    ///   `k = 14779` lands on it.
    /// - `s = 0`: on the reference group with `x = 7` and the digest
    ///   `0x14ec`, the first candidate `k = 29681` gives `r = 8598` and
    ///   `z + xr ≡ 0 (mod q)`.
    #[test]
    fn deterministic_signing_retries_zero_r_and_s() {
        for (p, g, x, digest, rejected, r, s) in [
            (1_179_757, 991_000, 3, [0x13, 0xa4], 14779, 22939, 6802), // r = 0 first
            (P, G, 7, [0x14, 0xec], 29681, 11359, 28970),              // s = 0 first
        ] {
            let (public, private) =
                Dsa::from_secret_exponent(&u(p), &u(Q), &u(g), &u(x)).expect("valid toy domain");
            assert!(private
                .sign_digest_with_nonce(&digest, &u(rejected))
                .is_none());
            let signature = private.sign_digest::<Sha256>(&digest).expect("retry");
            assert_eq!(signature.r(), &u(r));
            assert_eq!(signature.s(), &u(s));
            assert!(public.verify(&digest, &signature));
            assert_eq!(private.sign_digest::<Sha256>(&digest), Some(signature));
        }
    }

